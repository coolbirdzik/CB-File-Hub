// Regenerates rust/src/fold_table.rs from package:diacritic and this Dart
// SDK's String.toLowerCase.
//
// The app's Dart search lowercases names and folds them with
// `removeDiacritics` (see cb_file_manager/lib/helpers/core/text_utils.dart).
// The Rust matcher must do both identically, so all tables are derived from
// the Dart functions instead of being maintained by hand. Rust's own
// to_lowercase follows a newer Unicode version than Dart (Cherokee, for
// example), which is why lowercasing is a table too. Rerun after a Dart SDK
// upgrade; the parity test in cb_file_manager catches drift. Run from
// cb_native/:
//
//   dart run tool/gen_fold_table.dart
// ignore_for_file: avoid_print

import 'dart:io';

import 'package:diacritic/src/replacement_map.dart';

void main() {
  final entries = <String>[];
  // removeDiacritics works on UTF-16 code units and only maps BMP units.
  for (var unit = 0; unit <= 0xFFFF; unit++) {
    if (unit >= 0xD800 && unit <= 0xDFFF) continue;
    final replaced = replaceCodeUnits([unit]);
    if (replaced.length == 1 && replaced.first == unit) continue;
    // Combining marks (U+0300..U+036F) are dropped, encoded as an empty slice.
    final units = replaced.map((u) => '0x${u.toRadixString(16)}').join(', ');
    entries.add('    (0x${unit.toRadixString(16)}, &[$units]),');
  }

  final lower = _caseTable((value) => value.toLowerCase());
  final upper = _caseTable((value) => value.toUpperCase());

  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_fold_table.dart from package:diacritic and '
      'Dart toLowerCase/toUpperCase.',
    )
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('/// (UTF-16 unit, replacement units), sorted by unit.')
    ..writeln('pub static FOLD_TABLE: &[(u16, &[u16])] = &[')
    ..writeln(entries.join('\n'))
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// (code point, Dart toLowerCase result), sorted by code point.',
    )
    ..writeln('pub static LOWER_TABLE: &[(u32, &str)] = &[')
    ..writeln(lower.join('\n'))
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// (code point, Dart toUpperCase result), sorted by code point.',
    )
    ..writeln('pub static UPPER_TABLE: &[(u32, &str)] = &[')
    ..writeln(upper.join('\n'))
    ..writeln('];');

  final file = File('rust/src/fold_table.rs');
  file.writeAsStringSync(out.toString());
  print(
    'Wrote ${entries.length} fold, ${lower.length} lowercase and '
    '${upper.length} uppercase entries to ${file.path}',
  );
}

/// Every code point whose [convert] result differs from itself, as Rust
/// `(code point, "replacement")` rows.
List<String> _caseTable(String Function(String) convert) {
  final rows = <String>[];
  for (var rune = 0; rune <= 0x10FFFF; rune++) {
    if (rune >= 0xD800 && rune <= 0xDFFF) continue;
    final original = String.fromCharCode(rune);
    final converted = convert(original);
    if (converted == original) continue;
    final escaped = converted.runes
        .map((r) => '\\u{${r.toRadixString(16)}}')
        .join();
    rows.add('    (0x${rune.toRadixString(16)}, "$escaped"),');
  }
  return rows;
}
