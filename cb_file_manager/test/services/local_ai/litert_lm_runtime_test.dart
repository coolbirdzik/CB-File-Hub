import 'package:cb_file_manager/models/local_ai/local_ai_advisor_model.dart';
import 'package:cb_file_manager/services/local_ai/litert_lm_runtime.dart';
import 'package:flutter_edge_ai/flutter_edge_ai.dart';
import 'package:flutter_test/flutter_test.dart';

InstalledLocalModel _model(String id, String file) => InstalledLocalModel(
  catalogId: id,
  displayName: id,
  localPath: '/models/$file',
  sizeBytes: 1,
  installedAt: DateTime(2026),
  runtimeArtifactId: file,
);

Map<String, String> _m(String role, String content) => {
  'role': role,
  'content': content,
};

void main() {
  group('session reuse', () {
    final history = [
      _m('user', 'find my contract'),
      _m('assistant', '<think>x</think><tool_call>{"name":"search_files"}'),
    ];

    test('a tool round only extends the conversation', () {
      final next = [
        _m('user', 'find my contract'),
        // The agent strips reasoning from what the model wrote.
        _m('assistant', '<tool_call>{"name":"search_files"}'),
        _m('tool', '{"ok":true,"items":[]}'),
      ];
      expect(LiteRtLmLocalAiChatRuntime.continues(history, next), isTrue);
      expect(
        LiteRtLmLocalAiChatRuntime.renderTurn(
          next.sublist(history.length),
          hasEarlierTurns: true,
        ),
        '[tool]\n{"ok":true,"items":[]}',
      );
    });

    test('an edited, trimmed or replayed conversation starts afresh', () {
      expect(
        LiteRtLmLocalAiChatRuntime.continues(history, [
          _m('user', 'find my invoice'),
          history[1],
          _m('user', 'and the other one'),
        ]),
        isFalse,
      );
      expect(
        LiteRtLmLocalAiChatRuntime.continues(history, history.sublist(0, 1)),
        isFalse,
      );
      // New assistant turns were not generated by this session.
      expect(
        LiteRtLmLocalAiChatRuntime.continues(history, [
          ...history,
          _m('user', 'next'),
          _m('assistant', 'made up'),
        ]),
        isFalse,
      );
      expect(LiteRtLmLocalAiChatRuntime.continues(const [], history), isFalse);
    });

    test('a fresh session receives earlier turns as a transcript', () {
      expect(
        LiteRtLmLocalAiChatRuntime.renderTurn([
          _m('user', 'hello'),
        ], hasEarlierTurns: false),
        'hello',
      );
      final turn = LiteRtLmLocalAiChatRuntime.renderTurn([
        _m('user', 'find my contract'),
        _m('assistant', 'Which folder?'),
        _m('user', 'Documents'),
      ], hasEarlierTurns: false);
      expect(turn, startsWith('Conversation so far:'));
      expect(turn, contains('[assistant]\nWhich folder?'));
      expect(turn, endsWith('[user]\nDocuments'));
    });
  });

  test('each model gets its own chat template', () {
    ModelType type(String id, String file) =>
        LiteRtLmLocalAiChatRuntime.modelTypeFor(_model(id, file));

    expect(
      type(
        'litert-community/gemma-4-E2B-it-litert-lm',
        'gemma-4-E2B-it.litertlm',
      ),
      ModelType.gemma4,
    );
    expect(
      type(
        'litert-community/functiongemma-270m-ft-mobile-actions',
        'mobile_actions_q8_ekv1024.litertlm',
      ),
      ModelType.functionGemma,
    );
    expect(
      type('litert-community/Qwen3.5-0.8B', 'Qwen3.5-0.8B_int8.litertlm'),
      ModelType.qwen35,
    );
    expect(
      type(
        'litert-community/Qwen3-1.7B',
        'Qwen3-1.7B_dynamic_wi4b32_afp32.litertlm',
      ),
      ModelType.qwen3,
    );
    expect(
      type('litert-community/Qwen3-4B-Instruct-2507', 'qwen3_4b_2507.litertlm'),
      ModelType.qwen,
    );
    expect(
      type('litert-community/Gemma3-1B-IT', 'gemma3-1b-it.litertlm'),
      ModelType.gemmaIt,
    );
  });
}
