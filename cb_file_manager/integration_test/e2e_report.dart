// E2E screenshot capture + persisted manifest.
//
// Usage inside a testWidgets() call:
//   final et = E2ETester(tester);
//   await et.init('test name');           // captures '00_initial'
//   await et.tap(...);                    // auto-screenshot per action
//   await et.screenshot('result');        // manual checkpoint
//   await et.pass();   // or et.fail()    // record final status
//
// Output is written to:
//   build/e2e_report/screenshots/*.png   ← captured frames
//   build/e2e_report/manifest.json       ← step labels + status, consumed by
//                                          tool/e2e_dashboard.dart
//
// The unified dashboard at build/e2e_dashboard/index.html is generated by
// `dart run tool/e2e_dashboard.dart` (called automatically by the e2e make
// targets). The dashboard reads this manifest to render every step's
// screenshot inline with a lightbox viewer.
//
// The manifest is rewritten after every captured screenshot so partial state
// is preserved even if later tests crash. Screenshots from previous runs of
// the SAME test are cleared on `et.init()`; results from OTHER tests are
// preserved so partial reruns don't wipe the dashboard.

