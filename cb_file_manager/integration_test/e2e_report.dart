Future<void> _ensureReportDir() async {
  if (_reportDir != null) return;
  _reportDir = Directory(
    p.join(await _reportRootPath(), 'build', 'e2e_report'),
  );
  _screenshotsDir = Directory(p.join(_reportDir!.path, 'screenshots'));
  await _screenshotsDir!.create(recursive: true);
  if (kDebugMode) {
    debugPrint('[E2E Report] Output directory: ${_reportDir!.path}');
  }
  await _loadManifest();
}

/// Root the report tree is written under.
///
/// On desktop the test process runs from the Flutter project directory, so
/// `build/e2e_report` lands next to the other build artifacts. On Android the
/// process runs inside the app sandbox where `Directory.current` is `/` and
/// not writable, so the report goes to the app's own external files directory
/// instead — a location `adb pull` can fetch after the run (see
/// `scripts/capture_screenshots.*`).
Future<String> _reportRootPath() async {
  if (!Platform.isAndroid) return Directory.current.path;

  // Ask the platform for the app's external files directory. This has to go
  // through the pre-sandbox provider: the sandbox redirects every path_provider
  // call into a throwaway temp dir the host cannot reach. Going through the
  // plugin also matters because `Android/data/<package>/files` is created by
  // the framework — a fresh install leaves it absent, and the app cannot mkdir
  // it itself under scoped storage.
  try {
    final external = await E2ESandboxPaths.platformProvider
        .getExternalStoragePath();
    if (external != null && external.isNotEmpty) {
      final root = Directory(p.join(external, 'cb_e2e'));
      root.createSync(recursive: true);
      return root.path;
    }
  } catch (_) {
    // Fall through to the fixed candidates below.
  }

  for (final base in kAndroidReportRoots) {
    try {
      Directory(base).createSync(recursive: true);
      return base;
    } catch (_) {
      // Try the next candidate.
    }
  }

  return Directory.current.path;
}

/// Fallback on-device roots for the Android report tree, most preferred first.
/// Only used when the platform cannot report an external files directory.
const List<String> kAndroidReportRoots = <String>[
  '/sdcard/Android/data/com.cbv.filehub/files/cb_e2e',
  '/storage/emulated/0/Android/data/com.cbv.filehub/files/cb_e2e',
  '/sdcard/Download/cb_e2e',
];

// ---------------------------------------------------------------------------
// Manifest — persists screenshot log + test results across process runs so
// reruns of a subset of tests don't wipe earlier results from the dashboard.
// ---------------------------------------------------------------------------

File? get _manifestFile =>
    _reportDir == null ? null : File(p.join(_reportDir!.path, 'manifest.json'));

Future<void> _loadManifest() async {
  if (_manifestLoaded) return;
  _manifestLoaded = true;
  final f = _manifestFile;
  if (f == null || !await f.exists()) return;
  try {
    final content = await f.readAsString();
    if (content.trim().isEmpty) return;
    final decoded = jsonDecode(content);
    if (decoded is! Map) return;

    final entries = decoded['entries'];
    if (entries is List) {
      for (final e in entries) {
        if (e is! Map) continue;
        final tn = e['testName'] as String?;
        final step = e['step'] as String?;
        final fname = e['filename'] as String?;
        final ts = e['ts'] as String?;
        if (tn == null || step == null || fname == null) continue;
        _log.add(
          _Entry(
            testName: tn,
            step: step,
            filename: fname,
            ts: ts != null
                ? (DateTime.tryParse(ts) ?? DateTime.now())
                : DateTime.now(),
          ),
        );
      }
    }

    final results = decoded['results'];
    if (results is Map) {
      for (final entry in results.entries) {
        final key = entry.key;
        final val = entry.value;
        if (key is String && val is bool) _testResults[key] = val;
      }
    }

    final counter = decoded['counter'];
    if (counter is int && counter > _counter) _counter = counter;

    if (kDebugMode) {
      debugPrint(
        '[E2E Report] Manifest loaded: ${_log.length} screenshot(s), '
        '${_testResults.length} test result(s)',
      );
    }
  } catch (_) {}
}

Future<void> _saveManifest() async {
  final f = _manifestFile;
  if (f == null) return;
  try {
    final entries = _log
        .map(
          (e) => {
            'testName': e.testName,
            'step': e.step,
            'filename': e.filename,
            'ts': e.ts.toIso8601String(),
          },
        )
        .toList();
    final body = {
      'entries': entries,
      'results': _testResults,
      'counter': _counter,
      'updatedAt': DateTime.now().toIso8601String(),
    };
    await f.writeAsString(jsonEncode(body));
  } catch (_) {}
}

/// Removes all entries for [testName] from the in-memory log and deletes the
/// on-disk screenshot files. Called on the first `init()` for a test in this
/// process so reruns produce clean output without losing other tests' results.
///
/// Idempotent within a single process — subsequent calls for the same test
/// (e.g. from manual `screenshot()` calls) are no-ops so we don't wipe
/// in-progress captures.
Future<void> _clearTestEntries(String testName) async {
  if (_clearedThisRun.contains(testName)) return;
  _clearedThisRun.add(testName);

  final stale = _log.where((e) => e.testName == testName).toList();
  if (stale.isEmpty) return;

  _log.removeWhere((e) => e.testName == testName);

  if (_screenshotsDir == null) return;
  for (final e in stale) {
    try {
      final file = File(p.join(_screenshotsDir!.path, e.filename));
      if (await file.exists()) await file.delete();
    } catch (_) {}
  }

  if (kDebugMode) {
    debugPrint(
      '[E2E Report] Cleared ${stale.length} stale screenshot(s) for "$testName"',
    );
  }
}

String _slugify(String s) => s
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
    .replaceAll(RegExp(r'^_+|_+$'), '');

String _esc(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
