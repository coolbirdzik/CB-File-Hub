// ---------------------------------------------------------------------------
// Internal state
// ---------------------------------------------------------------------------

class _Entry {
  final String testName;
  final String step;
  final String filename;
  final DateTime ts;
  _Entry({
    required this.testName,
    required this.step,
    required this.filename,
    required this.ts,
  });
}

/// Upper bound for every settle performed by this reporter.
///
/// `pumpAndSettle` defaults to a ten minute timeout. A screen that never stops
/// animating — a video thumbnail placeholder still waiting on its decoder, for
/// example — therefore blocks a capture run for ten minutes per frame before
/// the surrounding try/catch can fall back to a plain pump. Capturing a
/// still-loading frame is always preferable to losing the run.
const Duration kE2ESettleTimeout = Duration(seconds: 12);

final List<_Entry> _log = [];
Directory? _reportDir;
Directory? _screenshotsDir;
int _counter = 0;
bool _manifestLoaded = false;

/// Tests cleared during the current process run. We only clear a test's
/// previous screenshots once per process — on the first `init()` call —
/// so multiple `screenshot()` calls within the same test don't wipe each
/// other out.
final Set<String> _clearedThisRun = {};

/// Stores test results so the HTML report can show pass/fail badges.
/// Key = test name, Value = true (passed) / false (failed).
final Map<String, bool> _testResults = {};

/// Records the result of a test for the HTML report.
///
/// Call this at the end of each `testWidgets()` test:
///   await recordTestResult('my test', true);   // passed
///   await recordTestResult('my test', false);  // failed
///
/// If not called, the test shows with no badge (unknown status).
void recordTestResult(String testName, bool passed) {
  _testResults[testName] = passed;
  _writeResultsJson(); // persist so e2e_parallel can read it after merge
  _saveManifest();
}

/// Exports _testResults to build/e2e_report/results.json so e2e_parallel
/// Writes `results.json` with the bool pass/fail map. Kept as a side artifact
/// for tooling that still grep's for it (e.g. external CI dashboards). The
/// authoritative data store is `manifest.json`.
Future<void> _writeResultsJson() async {
  if (_reportDir == null) return;
  try {
    final file = File(p.join(_reportDir!.path, 'results.json'));
    final entries = _testResults.entries
        .map((e) => '  "${_esc(e.key)}": ${e.value}')
        .join(',\n');
    await file.writeAsString('{\n$entries\n}');
  } catch (_) {}
}

